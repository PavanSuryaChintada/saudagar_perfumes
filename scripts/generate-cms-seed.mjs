// Builds supabase/migrations/0011_seed_cms.sql from supabase/seed/cms.json and supabase/seed/pages.json.
// The migration only fills what is missing, so re-running it never overwrites edits made in the admin.
// Usage: node scripts/generate-cms-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const cms = read('supabase/seed/cms.json');
const pages = read('supabase/seed/pages.json');

// Dollar-quoted literal with a tag that cannot occur in the text.
function lit(value) {
  if (value === null || value === undefined) return 'null';
  const s = typeof value === 'string' ? value : JSON.stringify(value);
  let tag = 'q';
  while (s.includes(`$${tag}$`)) tag += 'q';
  return `$${tag}$${s}$${tag}$`;
}
const json = (v) => `${lit(v ?? {})}::jsonb`;
const bool = (v, d) => (v === undefined ? String(d) : String(Boolean(v)));
const int = (v, d) => (Number.isInteger(v) ? String(v) : String(d));
const productId = (slug) => (slug ? `(select id from public.products where slug = ${lit(slug)})` : 'null::uuid');

const out = [];
out.push('-- 0011_seed_cms: the storefront content as it looked before the CMS, now editable in the admin.');
out.push('-- Generated by scripts/generate-cms-seed.mjs from supabase/seed/cms.json and supabase/seed/pages.json. Do not edit by hand.');
out.push('-- Each table is filled only when it is empty (blocks and pages: only when the key or slug is missing).');
out.push('');

out.push('-- Site blocks');
for (const [key, value] of Object.entries(cms.blocks)) {
  out.push(`insert into public.site_blocks (key, value) values (${lit(key)}, ${json(value)}) on conflict (key) do nothing;`);
}
out.push('');

out.push('-- Pages and their sections');
for (const p of pages) {
  out.push(`with page as (
  insert into public.pages (slug, title, layout, body, seo_title, seo_description, is_published, is_system, position)
  values (${lit(p.slug)}, ${lit(p.title)}, ${lit(p.layout)}, ${lit(p.body)}, ${lit(p.seo_title)}, ${lit(p.seo_description)}, ${bool(p.is_published, true)}, ${bool(p.is_system, false)}, ${int(p.position, 0)})
  on conflict (slug) do nothing
  returning id
)`);
  if (p.sections.length) {
    const rows = p.sections.map(
      (s, i) => `  ((select id from page), ${lit(s.type)}, ${lit(s.label)}, ${i}, ${bool(s.is_visible, true)}, ${json(s.config)})`,
    );
    out.push(`insert into public.website_sections (page_id, section_type, label, position, is_visible, config)
select * from (values
${rows.join(',\n')}
) v(page_id, section_type, label, position, is_visible, config)
where v.page_id is not null;`);
  } else {
    out.push('select 1 from page;');
  }
}
out.push('');

function seedTable(table, rows, columns, toValues) {
  if (!rows.length) return;
  out.push(`-- ${table}`);
  out.push(`insert into public.${table} (${columns.join(', ')})
select * from (values
${rows.map((r, i) => `  (${toValues(r, i).join(', ')})`).join(',\n')}
) v(${columns.join(', ')})
where not exists (select 1 from public.${table});`);
  out.push('');
}

seedTable('announcements', cms.announcements, ['text', 'link', 'is_active', 'position'], (r, i) => [
  lit(r.text), r.link ? json(r.link) : 'null::jsonb', bool(r.is_active, true), String(i),
]);
seedTable('stories', cms.stories, ['title', 'subtitle', 'tag', 'image_url', 'video_url', 'duration_ms', 'product_id', 'is_active', 'position'], (r, i) => [
  lit(r.title), lit(r.subtitle), lit(r.tag), lit(r.image_url), lit(r.video_url), int(r.duration_ms, 5000), productId(r.product_slug), bool(r.is_active, true), String(i),
]);
seedTable('testimonials', cms.testimonials, ['quote', 'name', 'location', 'rating', 'product_id', 'is_active', 'position'], (r, i) => [
  lit(r.quote), lit(r.name), lit(r.location), Number.isInteger(r.rating) ? String(r.rating) : 'null::int', productId(r.product_slug), bool(r.is_active, true), String(i),
]);
seedTable('stockists', cms.stockists, ['name', 'city', 'address', 'phone', 'hours', 'map_url', 'image_url', 'is_active', 'position'], (r, i) => [
  lit(r.name), lit(r.city), lit(r.address), lit(r.phone), lit(r.hours), lit(r.map_url), lit(r.image_url), bool(r.is_active, true), String(i),
]);
seedTable('faqs', cms.faqs || [], ['question', 'answer', 'group_name', 'is_active', 'position'], (r, i) => [
  lit(r.question), lit(r.answer), lit(r.group_name), bool(r.is_active, true), String(i),
]);

if (cms.reels.length) {
  out.push('-- reels and the products tagged in them');
  out.push(`do $reels$
declare
  r record;
  new_id uuid;
begin
  if exists (select 1 from public.reels) then
    return;
  end if;
  for r in
    select * from jsonb_to_recordset(${json(cms.reels.map((x, i) => ({ ...x, position: i })))})
      as t(title text, caption text, video_url text, thumbnail_url text, external_url text, product_slugs text[], is_active boolean, position int)
  loop
    insert into public.reels (title, caption, video_url, thumbnail_url, external_url, is_active, position)
    values (r.title, r.caption, r.video_url, r.thumbnail_url, r.external_url, coalesce(r.is_active, true), r.position)
    returning id into new_id;
    insert into public.reel_products (reel_id, product_id, position)
    select new_id, p.id, s.ord - 1
    from unnest(coalesce(r.product_slugs, '{}')) with ordinality as s(slug, ord)
    join public.products p on p.slug = s.slug;
  end loop;
end
$reels$;`);
  out.push('');
}

const file = path.join(root, 'supabase/migrations/0011_seed_cms.sql');
fs.writeFileSync(file, out.join('\n'));
console.log(`Wrote ${path.relative(root, file)} (${pages.length} pages, ${pages.reduce((n, p) => n + p.sections.length, 0)} sections)`);
